from decimal import Decimal, InvalidOperation

from django import template
from django.utils.safestring import mark_safe

register = template.Library()


@register.filter
def num(value, decimals=0):
    """Format angka gaya Indonesia: 1000 -> 1.000, 1234.5 -> 1.234,5"""
    if value is None or value == "":
        return "-"
    try:
        value = Decimal(str(value))
    except (InvalidOperation, TypeError, ValueError):
        return value
    decimals = int(decimals)
    formatted = f"{value:,.{decimals}f}"
    # Tukar pemisah: koma -> titik, titik -> koma
    formatted = formatted.replace(",", "X").replace(".", ",").replace("X", ".")
    return formatted


@register.filter
def pct(value, decimals=2):
    """Format persentase: 3.1666 -> 3,17%"""
    if value is None or value == "":
        return "-"
    try:
        value = Decimal(str(value))
    except (InvalidOperation, TypeError, ValueError):
        return value
    decimals = int(decimals)
    formatted = f"{value:,.{decimals}f}"
    formatted = formatted.replace(",", "X").replace(".", ",").replace("X", ".")
    return f"{formatted}%"


@register.filter
def severity_badge(severity):
    return {
        "critical": "badge-critical",
        "major": "badge-major",
        "minor": "badge-minor",
    }.get(severity, "badge-minor")


@register.filter
def severity_label(severity):
    return {
        "critical": "Critical",
        "major": "Major",
        "minor": "Minor",
    }.get(severity, severity)


@register.simple_tag(takes_context=True)
def querystring(context, **kwargs):
    """Bangun ulang query string dengan mempertahankan filter yang ada."""
    request = context.get("request")
    params = request.GET.copy() if request else {}
    for key, value in kwargs.items():
        if value in (None, ""):
            params.pop(key, None)
        else:
            params[key] = value
    return params.urlencode() if hasattr(params, "urlencode") else ""


@register.filter
def getattr_or(value, name):
    return getattr(value, name, "")


